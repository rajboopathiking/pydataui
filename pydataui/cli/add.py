"""
CLI Component Ingester for PyDataUI (pydataui add).
Fetches upcoming and community shadcn/ui components from official and 3rd-party
JSON registries and transpiles them into clean, pure Python component modules.
Zero Node.js, zero npm, zero frontend build step.
"""
from __future__ import annotations
import json
import os
import re
import sys
import urllib.request
from pathlib import Path
from typing import Any, Dict, Optional


OFFICIAL_REGISTRY_BASE = "https://ui.shadcn.com/r/styles/default"


def _clean_component_name(name: str) -> str:
    return name.lower().replace("-", "_").replace(" ", "_")


def _to_pascal_case(name: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[-_ ]+", name) if part)


def fetch_registry_schema(component_or_url: str) -> Dict[str, Any]:
    """Fetches component JSON schema from official shadcn registry or direct URL."""
    url = component_or_url
    if not (url.startswith("http://") or url.startswith("https://")):
        # Treat as official shadcn component name
        comp_name = component_or_url.lower().replace("_", "-")
        url = f"{OFFICIAL_REGISTRY_BASE}/{comp_name}.json"

    req = urllib.request.Request(
        url,
        headers={"User-Agent": "PyDataUI-CLI/1.1.1 (Component Ingester)"}
    )
    try:
        with urllib.request.urlopen(req, timeout=8) as response:
            return json.loads(response.read().decode("utf-8"))
    except Exception as e:
        # Fallback scaffold for offline usage or novel components
        comp_name = Path(component_or_url).stem
        return {
            "name": comp_name,
            "type": "registry:ui",
            "tailwind": "rounded-xl border bg-card text-card-foreground shadow-sm p-4",
            "files": []
        }


def generate_python_component_code(schema: Dict[str, Any], component_name: str) -> str:
    """Transpiles a shadcn JSON schema into a pure Python Component module."""
    class_name = _to_pascal_case(schema.get("name") or component_name)
    tag = schema.get("tag", "div")
    base_classes = schema.get("tailwind", "rounded-xl border bg-card text-card-foreground shadow-sm p-4")

    # If registry schema contains files with JSX, extract classes and attributes
    files = schema.get("files", [])
    extracted_classes = []
    for f in files:
        content = f.get("content", "")
        # Extract Tailwind classes from className="..."
        matches = re.findall(r'className=["\']([^"\']+)["\']', content)
        for m in matches:
            extracted_classes.extend(m.split())

    initial_base = schema.get("tailwind", "")
    if extracted_classes:
        seen = set()
        clean_classes = []
        for c in extracted_classes:
            if c not in seen and not c.startswith("{") and not c.endswith("}"):
                seen.add(c)
                clean_classes.append(c)
        if clean_classes:
            base_classes = f"{initial_base} {' '.join(clean_classes[:20])}".strip()
    else:
        base_classes = initial_base or "rounded-xl border bg-card text-card-foreground shadow-sm p-4"

    code = f'''"""
Auto-generated by PyDataUI CLI (pydataui add {component_name}).
Pure Python shadcn/ui component with zero frontend JS dependency.
"""
from __future__ import annotations
from typing import Any, List, Optional
from pydataui.components.base import Component
from pydataui.utils import escape_html


class {class_name}(Component):
    """
    Pure Python {class_name} component.
    Styled with shadcn/ui Tailwind utility classes.
    """
    tag = '{tag}'
    BASE_CLASSES = "{base_classes}"

    def __init__(self, *children, variant: str = "default", **kwargs):
        super().__init__(*children, **kwargs)
        self.variant = variant

    def _get_classes(self) -> List[str]:
        classes = super()._get_classes()
        classes.append(self.BASE_CLASSES)
        return classes
'''
    return code


def add_component(args) -> None:
    """CLI handler for `pydataui add <component>`."""
    target = args.component
    output_dir = getattr(args, "dir", "components/shadcn")
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    # Ensure __init__.py exists
    init_file = out_path / "__init__.py"
    if not init_file.exists():
        init_file.write_text("# Auto-generated PyDataUI shadcn components package\n", encoding="utf-8")

    comp_name = Path(target).stem.replace(".json", "")
    py_module_name = _clean_component_name(comp_name)
    target_file = out_path / f"{py_module_name}.py"

    print(f"\n📦 [PyDataUI] Ingesting shadcn component '{target}'...")
    schema = fetch_registry_schema(target)
    code = generate_python_component_code(schema, comp_name)

    target_file.write_text(code, encoding="utf-8")
    class_name = _to_pascal_case(schema.get("name") or comp_name)

    # Append to __init__.py
    current_init = init_file.read_text(encoding="utf-8")
    export_stmt = f"from .{py_module_name} import {class_name}\n"
    if export_stmt not in current_init:
        init_file.write_text(current_init + export_stmt, encoding="utf-8")

    print(f"✨ Successfully generated pure Python component:")
    print(f"   📁 File: {target_file}")
    print(f"   🐍 Usage:")
    print(f"      from {output_dir.replace('/', '.')}.{py_module_name} import {class_name}")
    print(f"      my_{py_module_name} = {class_name}(\"Content...\")\n")
